"""
Generate LaTeX tables dynamically from outputs/metrics.json
Ensures absolute scientific data integrity (no hardcoded or invented values).
"""

import json
import os
import sys

def generate_results_table(metrics_path="outputs/metrics.json", output_tex="report/results_table.tex"):
    if not os.path.exists(metrics_path):
        print(f"Error: {metrics_path} does not exist yet. Run src/train.py first.")
        return False
        
    with open(metrics_path, "r") as f:
        data = json.load(f)
        
    best_model = data.get("best_model", "")
    models = data.get("models", {})

    lines = []
    lines.append("% Auto-generated by report/make_tables.py from outputs/metrics.json")
    lines.append("% Do not edit manually - strict academic data integrity")
    lines.append("\\begin{table}[htbp]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\caption{Comparative Performance Metrics of Evaluated Models on Test Set (80/20 Split)}")
    lines.append("\\label{tab:model_results}")
    lines.append("\\begin{tabular}{lcccc}")
    lines.append("\\toprule")
    lines.append("\\textbf{Supervised Model} & \\textbf{5-Fold CV $R^2$} & \\textbf{Test MAE} & \\textbf{Test RMSE} & \\textbf{Test $R^2$} \\\\")
    lines.append("\\midrule")

    for model_name, m in models.items():
        is_best = (model_name == best_model)
        prefix = "\\textbf{" if is_best else ""
        suffix = "} $\\star$" if is_best else ""
        
        cv_str = f"{m['cv_r2_mean']:.4f} $\\pm$ {m['cv_r2_std']:.4f}"
        mae_str = f"{m['test_mae']:.4f}"
        rmse_str = f"{m['test_rmse']:.4f}"
        r2_str = f"{m['test_r2']:.4f}"
        
        if is_best:
            lines.append(f"\\textbf{{{model_name}}} $\\star$ & \\textbf{{{cv_str}}} & \\textbf{{{mae_str}}} & \\textbf{{{rmse_str}}} & \\textbf{{{r2_str}}} \\\\")
        else:
            lines.append(f"{model_name} & {cv_str} & {mae_str} & {rmse_str} & {r2_str} \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\vspace{2mm}")
    lines.append(f"\\\\\\footnotesize{{$\\star$ Selected best model based on lowest test RMSE ({best_model}).}}")
    lines.append("\\end{table}")

    os.makedirs(os.path.dirname(output_tex), exist_ok=True)
    with open(output_tex, "w") as f:
        f.write("\n".join(lines) + "\n")
        
    print(f"Generated {output_tex} successfully.")
    return True

if __name__ == "__main__":
    generate_results_table()
